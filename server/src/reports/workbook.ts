import ExcelJS from 'exceljs';
import type { WeeklyReport } from './weekly';

const INK = 'FF1F2937';
const HEADER_BG = 'FF1F2937';
const HEADER_FG = 'FFFFFFFF';
const BAND = 'FFF3F4F6';
const ACCENT = 'FF2563EB';
const WARN_BG = 'FFFEF2F2';
const WARN_FG = 'FF991B1B';

type Col = { header: string; key: string; width: number; numFmt?: string; wrap?: boolean };

function titleBlock(sheet: ExcelJS.Worksheet, report: WeeklyReport, subtitle: string, span: number) {
  sheet.mergeCells(1, 1, 1, span);
  const title = sheet.getCell(1, 1);
  title.value = `${report.title} — ${report.from} to ${report.to}`;
  title.font = { size: 15, bold: true, color: { argb: INK } };
  title.alignment = { vertical: 'middle' };
  sheet.getRow(1).height = 24;

  sheet.mergeCells(2, 1, 2, span);
  const sub = sheet.getCell(2, 1);
  sub.value = `${report.scopeLabel}   ·   ${subtitle}   ·   Generated by ${report.generatedBy} on ${report.generatedAt.slice(0, 16).replace('T', ' ')} UTC`;
  sub.font = { size: 10, color: { argb: 'FF6B7280' } };
  sheet.getRow(3).height = 6;
}

function writeTable<T extends Record<string, unknown>>(
  sheet: ExcelJS.Worksheet,
  cols: Col[],
  rows: T[],
  headerRowIndex: number
) {
  const headerRow = sheet.getRow(headerRowIndex);
  cols.forEach((c, i) => {
    const cell = headerRow.getCell(i + 1);
    cell.value = c.header;
    cell.font = { bold: true, color: { argb: HEADER_FG }, size: 10 };
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: HEADER_BG } };
    cell.alignment = { vertical: 'middle', horizontal: 'left', wrapText: true };
    sheet.getColumn(i + 1).width = c.width;
  });
  headerRow.height = 20;

  rows.forEach((row, r) => {
    const excelRow = sheet.getRow(headerRowIndex + 1 + r);
    cols.forEach((c, i) => {
      const cell = excelRow.getCell(i + 1);
      cell.value = (row[c.key] ?? '') as ExcelJS.CellValue;
      cell.font = { size: 10, color: { argb: INK } };
      cell.alignment = { vertical: 'top', wrapText: Boolean(c.wrap) };
      if (c.numFmt) cell.numFmt = c.numFmt;
      if (r % 2 === 1) {
        cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: BAND } };
      }
      cell.border = { bottom: { style: 'hair', color: { argb: 'FFE5E7EB' } } };
    });
  });

  if (rows.length > 0) {
    sheet.autoFilter = {
      from: { row: headerRowIndex, column: 1 },
      to: { row: headerRowIndex + rows.length, column: cols.length },
    };
  }
  sheet.views = [{ state: 'frozen', ySplit: headerRowIndex, xSplit: 0 }];
}

function highlightWhere(
  sheet: ExcelJS.Worksheet,
  headerRowIndex: number,
  rowCount: number,
  colCount: number,
  predicate: (rowIndex: number) => boolean
) {
  for (let r = 0; r < rowCount; r += 1) {
    if (!predicate(r)) continue;
    const row = sheet.getRow(headerRowIndex + 1 + r);
    for (let c = 1; c <= colCount; c += 1) {
      row.getCell(c).fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: WARN_BG } };
      row.getCell(c).font = { size: 10, color: { argb: WARN_FG } };
    }
  }
}

export async function buildWeeklyWorkbook(report: WeeklyReport): Promise<Buffer> {
  const wb = new ExcelJS.Workbook();
  wb.creator = 'Project Dashboard';
  wb.created = new Date();

  /* ---------- Sheet 1: Summary ---------- */
  const summary = wb.addWorksheet('Summary', { properties: { defaultRowHeight: 16 } });
  titleBlock(summary, report, 'Per-member roll-up', 10);

  const statRows: Array<[string, string | number]> = [
    ['Total hours logged', report.totals.hours],
    ['Log entries', report.totals.entries],
    ['People in scope', report.totals.members],
    ['People with no entries', report.totals.membersWithNoEntries],
    ['Tasks completed (all time)', report.totals.tasksDone],
    ['Entries flagged blocked', report.totals.blockedEntries],
    ['Outcomes delivered', report.totals.outcomes],
    ['Outcomes awaiting verification', report.totals.outcomesUnverified],
  ];
  statRows.forEach(([label, value], i) => {
    const row = summary.getRow(4 + i);
    const l = row.getCell(1);
    l.value = label;
    l.font = { size: 10, bold: true, color: { argb: 'FF6B7280' } };
    const v = row.getCell(2);
    v.value = value;
    v.font = { size: 11, bold: true, color: { argb: ACCENT } };
  });

  const memberCols: Col[] = [
    { header: 'Project', key: 'projectName', width: 26 },
    { header: 'Team', key: 'teamName', width: 22 },
    { header: 'Member', key: 'name', width: 22 },
    { header: 'Email', key: 'email', width: 28 },
    { header: 'Hours', key: 'hours', width: 9, numFmt: '0.00' },
    { header: 'Entries', key: 'entries', width: 9 },
    { header: 'Days logged', key: 'daysLogged', width: 12 },
    { header: 'Tasks touched', key: 'tasksTouched', width: 14 },
    { header: 'Open tasks', key: 'tasksOpen', width: 11 },
    { header: 'Done tasks', key: 'tasksDone', width: 11 },
  ];
  const memberHeaderRow = 4 + statRows.length + 1;
  writeTable(summary, memberCols, report.members as unknown as Record<string, unknown>[], memberHeaderRow);
  // Anyone who logged nothing all week is what the PM is scanning for.
  highlightWhere(summary, memberHeaderRow, report.members.length, memberCols.length, (i) => report.members[i].entries === 0);

  if (report.members.length > 0) {
    const totalRow = summary.getRow(memberHeaderRow + report.members.length + 1);
    totalRow.getCell(4).value = 'Total';
    totalRow.getCell(4).font = { bold: true, size: 10 };
    totalRow.getCell(5).value = { formula: `SUM(E${memberHeaderRow + 1}:E${memberHeaderRow + report.members.length})` };
    totalRow.getCell(5).numFmt = '0.00';
    totalRow.getCell(5).font = { bold: true, size: 10 };
    totalRow.getCell(6).value = { formula: `SUM(F${memberHeaderRow + 1}:F${memberHeaderRow + report.members.length})` };
    totalRow.getCell(6).font = { bold: true, size: 10 };
  }

  /* ---------- Sheet 2: Daily log ---------- */
  const daily = wb.addWorksheet('Daily Log', { properties: { defaultRowHeight: 16 } });
  titleBlock(daily, report, 'Every status entry in the week', 10);
  const logCols: Col[] = [
    { header: 'Date', key: 'date', width: 12 },
    { header: 'Project', key: 'projectName', width: 24 },
    { header: 'Team', key: 'teamName', width: 20 },
    { header: 'Member', key: 'memberName', width: 20 },
    { header: 'Task', key: 'taskTitle', width: 32, wrap: true },
    { header: 'Task status', key: 'taskStatus', width: 13 },
    { header: 'Hours', key: 'hours', width: 8, numFmt: '0.00' },
    { header: 'Entry status', key: 'status', width: 13 },
    { header: 'What was done', key: 'summary', width: 52, wrap: true },
    { header: 'Blockers', key: 'blockers', width: 34, wrap: true },
  ];
  writeTable(daily, logCols, report.logs as unknown as Record<string, unknown>[], 4);
  highlightWhere(daily, 4, report.logs.length, logCols.length, (i) => report.logs[i].status === 'BLOCKED');

  /* ---------- Sheet 3: Tasks ---------- */
  const tasks = wb.addWorksheet('Tasks', { properties: { defaultRowHeight: 16 } });
  titleBlock(tasks, report, 'Task board snapshot', 9);
  const taskCols: Col[] = [
    { header: 'Project', key: 'projectName', width: 24 },
    { header: 'Team', key: 'teamName', width: 20 },
    { header: 'Task', key: 'title', width: 38, wrap: true },
    { header: 'Assignee', key: 'assignee', width: 20 },
    { header: 'Status', key: 'status', width: 13 },
    { header: 'Priority', key: 'priority', width: 11 },
    { header: 'Due', key: 'dueDate', width: 12 },
    { header: 'Hours this week', key: 'hoursThisWeek', width: 16, numFmt: '0.00' },
    { header: 'Hours total', key: 'totalLoggedHours', width: 13, numFmt: '0.00' },
  ];
  writeTable(tasks, taskCols, report.tasks as unknown as Record<string, unknown>[], 4);
  highlightWhere(tasks, 4, report.tasks.length, taskCols.length, (i) => report.tasks[i].status === 'BLOCKED');

  /* ---------- Sheet 4: Outcomes ---------- */
  const outcomesSheet = wb.addWorksheet('Outcomes', { properties: { defaultRowHeight: 16 } });
  titleBlock(outcomesSheet, report, 'Delivered results, not activity', 8);
  const outcomeCols: Col[] = [
    { header: 'Date', key: 'landedOn', width: 12 },
    { header: 'Project', key: 'projectName', width: 24 },
    { header: 'Team', key: 'teamName', width: 20 },
    { header: 'Title', key: 'title', width: 34, wrap: true },
    { header: 'Category', key: 'category', width: 18 },
    { header: 'PM', key: 'pmName', width: 18 },
    { header: 'Verified', key: 'verified', width: 10 },
    { header: 'What happened', key: 'narrative', width: 52, wrap: true },
  ];
  writeTable(outcomesSheet, outcomeCols, report.outcomes as unknown as Record<string, unknown>[], 4);
  // Unverified outcomes are exactly what a Director scanning this sheet should check first.
  highlightWhere(outcomesSheet, 4, report.outcomes.length, outcomeCols.length, (i) => !report.outcomes[i].verified);

  const out = await wb.xlsx.writeBuffer();
  return Buffer.from(out);
}
